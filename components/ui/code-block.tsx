import {
  createHighlighter,
  createJavaScriptRegexEngine,
  type Highlighter,
  type ShikiTransformer,
} from "shiki";
import { cn } from "@/lib/utils";

const THEME = "vesper";

const LANGS = ["ts", "tsx", "bash", "json", "mdx", "text"] as const;

export type CodeLanguage = (typeof LANGS)[number];

let highlighterPromise: Promise<Highlighter> | undefined;

function getHighlighter() {
  highlighterPromise ??= createHighlighter({
    themes: [THEME],
    langs: [...LANGS],
    engine: createJavaScriptRegexEngine(),
  });

  return highlighterPromise;
}

const transparentBackground: ShikiTransformer = {
  pre(node) {
    const declarations = String(node.properties.style ?? "")
      .split(";")
      .map((declaration) => declaration.trim())
      .filter(
        (declaration) =>
          declaration && !declaration.startsWith("background-color"),
      );

    node.properties.style = [...declarations, "background-color: transparent"]
      .join("; ")
      .concat(";");
  },
};

async function highlightCode(code: string, lang: CodeLanguage) {
  "use cache";

  const highlighter = await getHighlighter();

  return highlighter.codeToHtml(code, {
    lang,
    theme: THEME,
    transformers: [transparentBackground],
  });
}

export async function CodeBlock({
  code,
  lang = "text",
  className,
}: {
  code: string;
  lang?: CodeLanguage;
  className?: string;
}) {
  const html = await highlightCode(code, lang);

  return (
    <div
      className={cn(
        "min-w-0 max-w-full overflow-x-auto rounded-2xl bg-foreground/5 p-5 font-mono text-xs leading-relaxed",
        className,
      )}
      // biome-ignore lint/security/noDangerouslySetInnerHtml: static HTML generated by Shiki from local source strings, never user input
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}
